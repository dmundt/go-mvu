import { readFile, writeFile } from "node:fs/promises";
import postcss from "postcss";

const root = new URL("../", import.meta.url);

// Copy only Open Props tokens that default CSS references (transitively).
// First file wins on duplicate names, so tinted oklch grays replace hex grays.
const openPropsFiles = [
  "props.gray-oklch.css",
  "props.colors.css",
  "props.indigo.css",
  "props.sizes.css",
  "props.fonts.css",
  "props.borders.css",
  "props.shadows.css",
  "props.easing.css"
];
const openProps = new Map();
for (const file of openPropsFiles) {
  const css = postcss.parse(await readFile(new URL(`node_modules/open-props/src/${file}`, root), "utf8"));
  for (const node of css.nodes) {
    if (node.type !== "rule" || !/^:where\((html|\*)\)$/.test(node.selector)) continue;
    node.walkDecls(decl => {
      if (decl.prop.startsWith("--") && !openProps.has(decl.prop)) openProps.set(decl.prop, decl.value);
    });
  }
}
const referenced = text => [...text.matchAll(/var\(\s*(--[\w-]+)/g)].map(match => match[1]);
const pending = [];
for (const file of ["base.css", "default.css", "shared.css"]) {
  pending.push(...referenced(await readFile(new URL(`theme/default/${file}`, root), "utf8")));
}
const used = new Set();
while (pending.length) {
  const name = pending.pop();
  if (used.has(name) || !openProps.has(name)) continue;
  used.add(name);
  pending.push(...referenced(openProps.get(name)));
}
const openPropsVersion = JSON.parse(await readFile(new URL("node_modules/open-props/package.json", root), "utf8")).version;
const tokens = [...openProps].filter(([name]) => used.has(name)).map(([name, value]) => `\t${name}: ${value};`);
await writeFile(new URL("theme/default/open-props.css", root),
  `/* Generated by npm run build:themes from open-props@${openPropsVersion}.\n` +
  `   Subset: tokens referenced by base.css, default.css, shared.css.\n` +
  `   MIT License, see LICENSE-open-props.txt. */\n\n:where(html) {\n${tokens.join("\n")}\n}\n`);
await writeFile(new URL("theme/default/LICENSE-open-props.txt", root),
  await readFile(new URL("node_modules/open-props/LICENSE", root), "utf8"));
console.log(`Built open-props subset: ${tokens.length} tokens`);
